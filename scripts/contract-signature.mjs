#!/usr/bin/env node
// Import Yariv's scanned signature into the function bundle.
//
//   node scripts/contract-signature.mjs ~/Desktop/signature.png
//
// Takes a photo or scan on white paper, trims it to the ink, knocks the white
// background out to transparency, and writes the result as base64 into
// netlify/functions/lib/signature-yariv.mjs.
//
// It goes into the FUNCTION BUNDLE, never public/ - a file under public/ would
// be a permanently downloadable copy of a real signature on a guessable URL.

import sharp from "sharp";
import { writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join, resolve } from "node:path";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const TARGET = join(ROOT, "netlify/functions/lib/signature-yariv.mjs");

// Anything lighter than this is paper, not ink.
const WHITE_CUTOFF = 205;
const MAX_W = 900;

const die = (m) => {
  console.error(`\n✗ ${m}\n`);
  process.exit(1);
};

const src = process.argv[2];
if (!src) die("שימוש: node scripts/contract-signature.mjs <path-to-signature.png>");
const file = resolve(src);
if (!existsSync(file)) die(`הקובץ לא נמצא: ${file}`);

const img = sharp(file).rotate(); // honour EXIF from a phone photo
const meta = await img.metadata();
console.log(`מקור: ${meta.width}×${meta.height} ${meta.format}`);

// Grayscale the ink, then use it as the alpha channel: dark stays, paper goes.
const gray = await img.clone().grayscale().raw().toBuffer({ resolveWithObject: true });
const { data, info } = gray;

const alpha = Buffer.alloc(info.width * info.height);
let minX = info.width, minY = info.height, maxX = -1, maxY = -1;

for (let i = 0; i < alpha.length; i++) {
  const v = data[i * info.channels];
  // Linear ramp from cutoff down to black, so edges stay soft rather than jagged.
  const a = v >= WHITE_CUTOFF ? 0 : Math.round(255 * (1 - v / WHITE_CUTOFF));
  alpha[i] = a;
  if (a > 40) {
    const x = i % info.width;
    const y = (i / info.width) | 0;
    if (x < minX) minX = x;
    if (y < minY) minY = y;
    if (x > maxX) maxX = x;
    if (y > maxY) maxY = y;
  }
}

if (maxX < 0) die("לא נמצא דיו בתמונה. נסו סריקה ברורה יותר על נייר לבן.");

const pad = 6;
const left = Math.max(0, minX - pad);
const top = Math.max(0, minY - pad);
const width = Math.min(info.width - left, maxX - minX + pad * 2);
const height = Math.min(info.height - top, maxY - minY + pad * 2);
console.log(`דיו נמצא: ${width}×${height} (חתוך מהמקור)`);

// Solid espresso ink + the computed alpha, so the signature matches the brand
// colour instead of whatever the camera's white balance decided.
const ink = await sharp({
  create: { width: info.width, height: info.height, channels: 3, background: { r: 69, g: 50, b: 38 } },
})
  .joinChannel(alpha, { raw: { width: info.width, height: info.height, channels: 1 } })
  .png()
  .toBuffer();

const out = await sharp(ink)
  .extract({ left, top, width, height })
  .resize({ width: Math.min(MAX_W, width), withoutEnlargement: true })
  .png({ compressionLevel: 9 })
  .toBuffer();

const b64 = out.toString("base64");
console.log(`PNG סופי: ${Math.round(out.length / 1024)}KB`);

writeFileSync(
  TARGET,
  `// Yariv's counter-signature, as a base64 PNG.
//
// It lives INSIDE the function bundle, never in public/. A file under public/
// would be a permanently downloadable copy of a real person's signature on a
// predictable URL. Bundled here, it never reaches a browser: the client leaves
// an empty box in the PDF and the server stamps it.
//
// Generated by scripts/contract-signature.mjs - re-run that to replace it.

export const YARIV_SIGNATURE_PNG =
  "${b64}";
`,
  "utf8",
);

console.log(`\n✓ נכתב אל netlify/functions/lib/signature-yariv.mjs`);
console.log(`  החתימה תוטמע אוטומטית בכל חוזה שייחתם מעכשיו.\n`);
